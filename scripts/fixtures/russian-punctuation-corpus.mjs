const prefixes = ['', 'Ранее он задумался. ', '— ', '🙂 '];
const capitalize = text => text[0].toUpperCase() + text.slice(1);
const lower = text => text[0].toLowerCase() + text.slice(1);

export const RUSSIAN_PUNCTUATION_CASES = turns.flatMap(([turn, clause], index) => {
  const split = clause.indexOf(' '), subject = capitalize(clause.slice(0, split)), predicate = clause.slice(split + 1);
  const layouts = [
    { position: 'initial', text: `${turn} ${clause}`, gold: `${turn}, ${clause}` },
    { position: 'medial', text: `${subject} ${lower(turn)} ${predicate}`, gold: `${subject}, ${lower(turn)}, ${predicate}` },
    { position: 'final', text: `${capitalize(clause.slice(0, -1))} ${lower(turn)}.`, gold: `${capitalize(clause.slice(0, -1))}, ${lower(turn)}.` },
  ];
  return layouts.flatMap(item => prefixes.map((prefix, context) => ({ id: `ru-gerund-${index + 1}-${item.position}-${context}`, position: item.position, text: prefix + item.text, gold: prefix + item.gold })));
});

